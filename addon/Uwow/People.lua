local function pick(t, form)
    if not t then return nil end
    local f = UnitSex and UnitSex("player") == 3
    if form == "v" then return f and t[4] or t[3] end
    return f and t[2] or t[1]
end

function U.ClassName(form)
    if not UnitClass then return "" end
    local _, file = UnitClass("player")
    return pick(CLASS[file or ""], form) or ""
end

function U.RaceName(form)
    if not UnitRace then return "" end
    local _, file = UnitRace("player")
    return pick(RACE[file or ""], form) or ""
end
